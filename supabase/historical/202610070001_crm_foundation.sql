create or replace function public.crm_audit_change() returns trigger
language plpgsql security definer set search_path = public as $$
declare fields text[]; begin
  if tg_op = 'UPDATE' then
    select array_agg(k) into fields from jsonb_object_keys(to_jsonb(new)) k
    where to_jsonb(new)->k is distinct from to_jsonb(old)->k;
  end if;
  insert into public.audit_logs(actor_id, entity, entity_id, action, changed_fields)
  values (auth.uid(), tg_table_name, new.id::text, tg_op, coalesce(fields, '{}'));
  return new;
end $$;
