create or replace function public.set_user_role(target_email text, new_role text) returns void
language plpgsql security definer set search_path = public as $$ declare target_id uuid; begin
  if not public.is_privilege_admin() then raise exception 'Apenas administradores podem alterar permissoes.' using errcode = '42501'; end if;
  if new_role not in ('admin','manager','broker','corretor','visitor') then raise exception 'Role invalida'; end if;
  select id into target_id from auth.users where email = target_email;
  if target_id is null then raise exception 'Usuario nao encontrado'; end if;
  update public.user_roles set role = new_role, updated_at = now() where id = target_id;
end $$;
