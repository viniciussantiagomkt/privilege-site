create or replace function public.crm_assign_lead(target_lead bigint, target_broker uuid, assignment_reason text)
returns void language plpgsql security definer set search_path = public as $$
declare previous_broker uuid; lead_name text; begin
  if not public.can_manage_operations() then raise exception 'Acesso negado' using errcode = '42501'; end if;
  if length(trim(coalesce(assignment_reason,''))) not between 1 and 500 then raise exception 'Informe o motivo da atribuicao'; end if;
  if not exists (select 1 from public.brokers b join public.user_roles r on r.id = b.id
    where b.id = target_broker and r.disabled_at is null and r.role in ('admin','manager','broker','corretor')) then
    raise exception 'Corretor invalido ou inativo';
  end if;
  select broker_id, name into previous_broker, lead_name from public.leads where id = target_lead for update;
  if not found then raise exception 'Lead nao encontrado'; end if;
  if previous_broker is not distinct from target_broker then return; end if;
  update public.leads set broker_id = target_broker, assigned_at = now() where id = target_lead;
  insert into public.lead_assignments(lead_id, previous_broker_id, broker_id, assigned_by, reason)
    values(target_lead, previous_broker, target_broker, auth.uid(), trim(assignment_reason));
  insert into public.lead_activities(lead_id,user_id,type,description)
    values(target_lead,auth.uid(),'lead_assigned',trim(assignment_reason));
  insert into public.notifications(user_id,title,description,type)
    values(target_broker,'Novo lead atribuido',lead_name,'lead_atribuido');
  update public.tasks set deleted_at = now(), updated_at = now() where lead_id = target_lead and broker_id = previous_broker and status <> 'concluida';
  insert into public.tasks(title,broker_id,lead_id,due_at)
    values('Primeiro contato: ' || left(coalesce(lead_name, 'Cliente'),120),target_broker,target_lead,now());
end $$;
revoke all on function public.crm_assign_lead(bigint,uuid,text) from public, anon;
grant execute on function public.crm_assign_lead(bigint,uuid,text) to authenticated;

