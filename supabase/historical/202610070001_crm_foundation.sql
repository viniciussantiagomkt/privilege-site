create or replace function public.current_user_role()
returns text
language sql
security definer
set search_path = public
stable
as $$
  select coalesce(
    (
      select role::text
      from public.user_roles
      where id = auth.uid()
        and disabled_at is null
      limit 1
    ),
    'visitor'
  );
$$;

