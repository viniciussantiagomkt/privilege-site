language plpgsql set search_path = public as $$ begin
  if new.origin_type is distinct from old.origin_type then
    raise exception 'A origem pessoal/institucional do lead e permanente.' using errcode = '42501';
  end if;
  if auth.uid() is not null and not public.can_manage_operations() and
    (new.broker_id is distinct from old.broker_id or new.source is distinct from old.source or new.origin_type is distinct from old.origin_type or new.assigned_at is distinct from old.assigned_at) then
    raise exception 'Somente a gestao pode alterar responsavel ou origem.' using errcode = '42501';
  end if;
  return new;
end $$;
